#!/usr/bin/env node
/**
 * Generate references/helix-extension-endpoints.md: every Helix endpoint whose name mentions "Extension"
 * (incl. Bits products, transactions, analytics, user extensions) with method, URL, auth type and the
 * documented rate limit — parsed from the official API reference so nothing is skipped.
 *
 * Usage: node scripts/gen-extension-endpoints.ts [path/to/api_reference.md]
 * Default input: the twitch-api skill's references/official/api_reference.md (sibling skill dir),
 * or $TWITCH_API_REFERENCE_MD. Run automatically by twitch-dev's refresh-docs.sh (gen-*.ts).
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const skillDir = resolve(here, '..');
const candidates = [
  process.argv[2],
  process.env.TWITCH_API_REFERENCE_MD,
  resolve(skillDir, '../twitch-api/references/official/api_reference.md'),
].filter((p): p is string => typeof p === 'string' && p.length > 0);
const input = candidates.find((p) => existsSync(p));
if (!input) {
  console.error('api_reference.md not found. Pass its path as the first argument. Tried:\n  ' + candidates.join('\n  '));
  process.exit(1);
}
const md = readFileSync(input, 'utf8');
const source = md.split('\n', 1)[0] ?? '';

interface Endpoint {
  name: string;
  anchor: string;
  method: string;
  url: string;
  auth: string;
  authKind: string;
  rateLimit: string;
  jwtClaims: string;
}

function clean(s: string): string {
  return s
    .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1') // links → text
    .replace(/\*\*/g, '')
    .replace(/\s+/g, ' ')
    .replace(/\|/g, '\\|')
    .trim();
}

const sections = md.split(/\n(?=## )/);
const endpoints: Endpoint[] = [];
for (const sec of sections) {
  const head = /^## (.+?)\s+\{#([^}]+)\}/.exec(sec);
  if (!head) continue;
  const name = head[1]!.trim();
  if (!/extension/i.test(name)) continue;
  const urlLine = /`(GET|POST|PUT|PATCH|DELETE) (https:\/\/api\.twitch\.tv\/helix\/[^`\s]+)`/.exec(sec);
  if (!urlLine) continue;
  const authBlock = /### Authorization\s*\n+([\s\S]*?)(?=\n### |\n## |$)/.exec(sec)?.[1] ?? '';
  const authFirst = clean(authBlock.split(/\n\s*\n/).filter((p) => p.trim() && !p.trim().startsWith('```'))[0] ?? '');
  const rate = /\*\*Rate Limits?\*\*:?\s*([^\n]+)/.exec(sec)?.[1] ?? '';
  let authKind = 'see docs';
  if (/JSON Web Token|JWT/.test(authBlock)) authKind = 'EBS-signed JWT (role external)';
  else if (/app access token/i.test(authBlock) && /user access token/i.test(authBlock)) authKind = 'app or user token';
  else if (/app access token/i.test(authBlock)) authKind = 'app access token';
  else if (/user access token/i.test(authBlock)) authKind = 'user access token';
  const scopes = [...authBlock.matchAll(/\*\*([a-z]+:[a-z:_]+)\*\*/g)].map((m) => m[1]);
  if (scopes.length) authKind += ` (${[...new Set(scopes)].join(' / ')})`;
  const claims = [...authBlock.matchAll(/`(role|user_id|exp|channel_id|pubsub_perms)`/g)].map((m) => m[1]);
  endpoints.push({
    name,
    anchor: head[2]!,
    method: urlLine[1]!,
    url: urlLine[2]!.replace('https://api.twitch.tv/helix', ''),
    auth: authFirst,
    authKind,
    rateLimit: clean(rate),
    jwtClaims: [...new Set(claims)].join(', '),
  });
}

const out: string[] = [
  '# Helix endpoints for Extensions (generated)',
  '',
  `<!-- generated by scripts/gen-extension-endpoints.ts from ${source.replace(/^<!--\s*|\s*-->$/g, '')} — do not edit by hand -->`,
  '',
  'Base URL `https://api.twitch.tv/helix`. Every request also needs `Client-Id: <extension client id>`.',
  'EBS-JWT endpoints: `Authorization: Bearer <JWT you signed with the extension secret>` (see jwt-and-ebs.md).',
  'Token endpoints: `Authorization: Bearer <OAuth token>`; for Bits products and Extension Transactions the',
  'token must be an APP token of the EXTENSION\'s own client ID (client credentials; see the twitch-dev skill). Full details:',
  '`grep -n "^## <Name>" <twitch-api skill>/references/official/api_reference.md`.',
  '',
  '| Endpoint | Method & path | Auth | Required JWT claims | Rate limit (documented) |',
  '|---|---|---|---|---|',
  ...endpoints.map(
    (e) => `| ${e.name} | \`${e.method} ${e.url}\` | ${e.authKind} | ${e.jwtClaims || '—'} | ${e.rateLimit || '—'} |`,
  ),
  '',
  '## Hand-checked caveats (static text in the generator — re-verify after a docs refresh)',
  '',
  '- Send Extension Chat Message: the Authorization text lists only `role`/`user_id`, but its 401 list says the',
  '  `broadcaster_id` query parameter must match the JWT `channel_id` claim — always sign with `channel_id`.',
  '- Send Extension PubSub Message: `channel_id` = broadcaster ID + `pubsub_perms.send: ["broadcast"]` (or the',
  '  whisper targets) for one channel; `channel_id: "all"` + `send: ["global"]` + `is_global_broadcast: true` for all.',
  '  The Building guide additionally says "1 message per second per channel" and 5 KB per message.',
  '- Get Extension Live Channels returns `pagination` as a STRING cursor, not the usual object.',
  '- The scopes page lists `channel:manage:extensions` for Get User Active Extensions / Update User Extensions,',
  '  while the endpoint pages say `user:read:broadcast` / `user:edit:broadcast`. Request what the endpoint page says.',
  '- extension.bits_transaction.create (EventSub, webhook/conduit only — not WebSocket) is the push alternative to',
  '  polling Get Extension Transactions; see the twitch-eventsub skill.',
  '',
  '## Authorization text per endpoint (verbatim first paragraph)',
  '',
  ...endpoints.map((e) => `- **${e.name}** — ${e.auth}`),
  '',
  `${endpoints.length} endpoints.`,
  '',
];
const target = resolve(skillDir, 'references/helix-extension-endpoints.md');
writeFileSync(target, out.join('\n'));
console.log(`wrote ${target} (${endpoints.length} endpoints)`);
