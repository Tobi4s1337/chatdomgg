import { expect, it } from 'vitest';
import * as THREE from 'three';
import { AvatarCapeBlueprintSchema } from '@chatdom/shared';
import { MATERIALS } from '@chatdom/content/materials';
import { PORTRAIT_FIXTURES, capeCut, slotColours } from '@chatdom/content/avatar-style';
import { createVoxelMaterial } from '@chatdom/render';
import { capeObject, disposeCape } from '../avatar-builder/cape';
import { createCitizenRenderer, createWornCitizenLook } from './index';
import { meshStyledCitizen } from './style-adapter';

it('carries the worn builder appearance and exact cape paint without granting a cape', async () => {
  const base = PORTRAIT_FIXTURES[0]!.look;
  expect(createWornCitizenLook('unadorned', base).cape).toBeUndefined();
  const earned = { kind: 'tier-cloak' as const, id: 'earned', cloth: '#963411' as const, lining: '#78baf1' as const, trim: '#e7d12b' as const };
  const recipe = { ...base, earned: { ...base.earned, cape: earned, hood: { cloth: '#a65c37' as const, trim: '#e0b141' as const } } };
  const worn = createWornCitizenLook('worn', recipe, true);
  const cut = capeCut(earned, true);
  expect(AvatarCapeBlueprintSchema.parse(worn.cape)).toMatchObject({ shape: cut.shape, width: cut.width, length: cut.length, hem: cut.hem, mount: cut.mount, trimWidth: cut.trimWidth });
  expect(worn.capePaint).toEqual({ cloth: [150 / 255, 52 / 255, 17 / 255], lining: [120 / 255, 186 / 255, 241 / 255], trim: [231 / 255, 209 / 255, 43 / 255], dim: true });
  const expected = slotColours(recipe, { subLapsed: true }).hood;
  expect(meshStyledCitizen(worn).some(part => part.mesh.colours.some((_, i, a) => i % 3 === 0 && expected.every((v, c) => Math.abs(a[i + c]! - v) < 1e-6)))).toBe(true);
  const preview = capeObject(recipe, true)!;
  expect(preview.userData.cut).toEqual(cut);
  const scene = new THREE.Scene(), lighting = createVoxelMaterial(MATERIALS, 'avatar');
  const renderer = await createCitizenRenderer(scene, { registry: MATERIALS, material: lighting, looks: [worn] });
  renderer.update([{ id: 'person', look: 'worn', position: [0, 0, 0], heading: 0, distance: 0, moving: 0 }]);
  const cloth = scene.getObjectByName('Citizen cape cloth') as THREE.InstancedMesh;
  const paint = cloth.geometry.getAttribute('aCapePaintCloth');
  expect(cloth.geometry.getAttribute('aCapePaintLining')).toBeUndefined();
  expect(cloth.geometry.getAttribute('aCapePaintTrim')).toBeUndefined();
  const lining = cloth.geometry.getAttribute('aCapeRainbowA');
  const trim = cloth.geometry.getAttribute('aCapeRainbowB');
  expect([lining.getX(0), lining.getY(0), lining.getZ(0)]).toEqual(worn.capePaint!.lining.map(Math.fround));
  expect([trim.getX(0), trim.getY(0), trim.getZ(0)]).toEqual(worn.capePaint!.trim.map(Math.fround));
  expect([paint.getX(0), paint.getY(0), paint.getZ(0), paint.getW(0)]).toEqual([150 / 255, 52 / 255, 17 / 255, 2].map(Math.fround));
  const cheer = createWornCitizenLook('event', { ...recipe, earned: { ...recipe.earned, cape: { ...earned, kind: 'cheer' } } }, true);
  expect(cheer.capePaint?.dim).toBe(false);
  renderer.dispose(); lighting.dispose(); disposeCape(preview);
});
